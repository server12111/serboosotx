_EMOJI_PATTERN = re.compile(
    "|".join(re.escape(emoji) for emoji in sorted(EMOJI_MAP, key=len, reverse=True))
)


def pe(text: str) -> str:
    """Wraps known emoji glyphs in <tg-emoji> tags for HTML parse_mode. Unknown glyphs
    pass through unchanged (rendered as regular Unicode emoji)."""
    return _EMOJI_PATTERN.sub(
        lambda match: f'<tg-emoji emoji-id="{EMOJI_MAP[match.group(0)]}">{match.group(0)}</tg-emoji>',
        text,
    )
